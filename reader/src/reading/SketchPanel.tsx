import { type ReactNode, useEffect, useRef, useState } from "react";
import type { SceneImage, SketchManifest } from "../lib/types";

interface Props {
  manifest: SketchManifest | null;
  activeOrder: number;
  error: string | null;
  waitForPictures: boolean;
  onWaitChange?: (wait: boolean) => void; // left out when the reader may not change it (a study session)
  options: ReactNode; // the picture style and how often pictures change
  bookTitle: string; // shown small beside the logo in the picture's corner
  sample: boolean; // a sample's pictures come ready-made, never placeholders
  resizer: ReactNode; // a handle under the picture for making it larger or smaller
  onShown?: (scene: SceneImage) => void; // a new picture appeared (the study's log)
}

const PRELOAD = 4; // pictures fetched ahead of the reader

interface Shown {
  url: string;
  caption: string;
}

const DRIFTS = 4; // directions a picture slowly zooms and pans in, so a still picture feels alive

/** The same drift for the same picture, chosen from its address. */
function drift(url: string): number {
  let hash = 0;
  for (const ch of url) hash = (hash * 31 + ch.charCodeAt(0)) | 0;
  return Math.abs(hash) % DRIFTS;
}

/**
 * The picture for the scene being read. When the next picture is not drawn
 * yet, the current one stays; a new picture fades in over the previous one.
 * Each picture drifts slowly (a gentle zoom and pan), and the previous one
 * keeps its place in the page while the new one fades in, so its drift goes
 * on without a jump.
 */
export function SketchPanel(props: Props) {
  const { manifest, activeOrder, error, waitForPictures, onWaitChange, options, bookTitle, resizer } = props;
  const { sample, onShown } = props;
  const scene = manifest?.scenes.find((s) => s.first_sentence <= activeOrder && activeOrder <= s.last_sentence);
  const [layers, setLayers] = useState<Shown[]>([]); // the previous picture, then the current one
  const shown = layers.at(-1) ?? null;

  useEffect(() => {
    if (scene?.image_url && scene.image_url !== shown?.url) {
      const next = { url: scene.image_url, caption: scene.caption };
      setLayers((now) => [...now.filter((layer) => layer.url !== next.url).slice(-1), next]);
      onShown?.(scene);
    }
  }, [scene?.image_url, scene?.caption, shown]);

  // Fetch the next few pictures before they are needed, so each one appears the moment its scene starts.
  const fetched = useRef(new Set<string>());
  useEffect(() => {
    const upcoming = manifest?.scenes.filter((s) => s.last_sentence >= activeOrder && s.image_url).slice(0, PRELOAD);
    for (const { image_url: url } of upcoming ?? []) {
      if (!url || fetched.current.has(url)) continue;
      fetched.current.add(url);
      new Image().src = url;
    }
  }, [manifest, activeOrder]);

  const placeholder = !sample && manifest?.provider.startsWith("mock");
  const overBudget = manifest?.scenes.some((s) => s.error_code === "budget_exceeded");
  let note: string | null = null;
  if (error) note = `Pictures: ${error}. Retrying…`;
  else if (!manifest || manifest.status === "planning") note = "Planning the scenes…";
  else if (manifest.status === "failed")
    note =
      manifest.error_code === "daily_limit"
        ? "Today's spending limit is reached. Pictures carry on after midnight UTC, or raise IR_DAILY_SPEND_LIMIT_USD."
        : manifest.error_code === "provider_account"
          ? "Your AI key was refused: check it, and its credit, in your settings (.env)."
          : manifest.error_code === "plan_failed"
            ? "The pictures could not be planned just now. Trying again in a minute…"
            : "Pictures could not be planned for this section.";
  else if (overBudget) note = `This book's picture budget is used up (${manifest.sketches_used} of ${manifest.sketch_budget}).`;
  else if (scene?.error_code === "refused") note = "The picture service declined to draw this scene.";
  else if (scene?.status === "pending") note = "Drawing this scene…";

  return (
    <section className="sketch-panel" aria-label="Scene picture">
      <div className="sketch-frame">
        {layers.map((layer) => (
          <div
            key={layer.url}
            className={layer === shown ? "sketch-layer current" : "sketch-layer previous"}
            data-drift={drift(layer.url)}
          >
            <img className="sketch" src={layer.url} alt={layer === shown ? `Sketch: ${layer.caption}` : ""} />
          </div>
        ))}
        {!shown && <div className="sketch-empty">A sketch of each scene appears here as the story is read.</div>}
        <div className="sketch-bug" aria-hidden="true">
          <span className="bug-logo">Imagine-Reader</span>
          <span className="bug-title">{bookTitle}</span>
        </div>
        <span className="sketch-label">AI visual generated by Imagine-reader{placeholder ? " · placeholder" : ""}</span>
      </div>
      {resizer}
      <div className="sketch-meta">
        <span role="status">{note}</span>
        {onWaitChange && (
          <label>
            <input type="checkbox" checked={waitForPictures} onChange={(event) => onWaitChange(event.target.checked)} />
            Wait for each picture
          </label>
        )}
      </div>
      {options}
    </section>
  );
}
